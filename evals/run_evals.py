"""Eval harness: extraction accuracy on labelled public plugin repos (see rubric.md).

Usage:
  python evals/run_evals.py                # clone/cache repos, score extraction, write results.md
  python evals/run_evals.py --generate     # also generate listings with Claude (needs ANTHROPIC_API_KEY)
  python evals/run_evals.py --min-score 0.9   # exit 1 if the mean drops below a threshold (CI gate)
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE.parent / "src"))

from storelistingkit.adapters import extract_profile  # noqa: E402

CACHE = HERE / ".cache"


def checkout(case: dict) -> Path:
    dest = CACHE / case["id"]
    if not (dest / ".git").exists():
        dest.mkdir(parents=True, exist_ok=True)
        subprocess.run(["git", "init", "-q", str(dest)], check=True)
        subprocess.run(["git", "-C", str(dest), "remote", "add", "origin", case["repo"]], check=True)
    subprocess.run(["git", "-C", str(dest), "fetch", "-q", "--depth", "1", "origin", case["commit"]], check=True)
    subprocess.run(["git", "-C", str(dest), "checkout", "-q", "--force", "FETCH_HEAD"], check=True)
    return dest


def f1(pred: set, gold: set) -> float:
    if not pred and not gold:
        return 1.0
    tp = len(pred & gold)
    if tp == 0:
        return 0.0
    p, r = tp / len(pred), tp / len(gold)
    return 2 * p * r / (p + r)


def score(profile, exp: dict) -> tuple[float, dict]:
    pts = 0.0
    detail = {}
    for f in ("engine", "name", "display_name", "version"):
        got = getattr(profile, f)
        got = got.value if hasattr(got, "value") else got
        ok = got == exp[f]
        pts += ok
        detail[f] = "ok" if ok else f"{got!r} != {exp[f]!r}"
    ok = set(profile.engine_versions) == set(exp["engine_versions"])
    pts += ok
    detail["engine_versions"] = "ok" if ok else f"{profile.engine_versions} != {exp['engine_versions']}"
    mods = set(profile.module_names())
    mf1 = f1(mods, set(exp["modules"]))
    pts += 2 * mf1
    detail["modules"] = "ok" if mf1 == 1 else f"F1={mf1:.2f} extra={sorted(mods - set(exp['modules']))} " \
                                             f"missing={sorted(set(exp['modules']) - mods)}"
    ok = set(profile.platforms) == set(exp["platforms"])
    pts += ok
    detail["platforms"] = "ok" if ok else f"{profile.platforms} != {exp['platforms']}"
    return pts / 8, detail


def run_generate(profile) -> dict:
    from storelistingkit.generator import ClaudeGenerator, GenerationError
    from storelistingkit.models import ENGINE_STORES

    out = {}
    for store in ENGINE_STORES[profile.engine]:
        t0 = time.time()
        try:
            copy = ClaudeGenerator().generate(profile, store)
            out[store.value] = {"ok": True, "seconds": round(time.time() - t0, 1), "title": copy.title}
        except GenerationError as exc:
            out[store.value] = {"ok": False, "seconds": round(time.time() - t0, 1), "error": str(exc),
                                "problems": exc.problems}
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--generate", action="store_true")
    ap.add_argument("--min-score", type=float, default=0.0)
    ap.add_argument("--out", default=str(HERE / "results.md"))
    args = ap.parse_args()

    cases = json.loads((HERE / "cases.json").read_text())["cases"]
    rows, results = [], []
    for case in cases:
        t0 = time.time()
        root = checkout(case)
        profile = extract_profile(root)
        s, detail = score(profile, case["expected"])
        ms = (time.time() - t0) * 1000
        res = {"id": case["id"], "score": s, "detail": detail, "ms": round(ms)}
        if args.generate:
            res["generate"] = run_generate(profile)
        results.append(res)
        misses = "; ".join(f"{k}: {v}" for k, v in detail.items() if v != "ok") or "—"
        rows.append(f"| {case['id']} | {profile.engine.value} | {s:.0%} | {misses} |")
        print(f"{case['id']:<22} {s:6.1%}  {misses}")

    mean = sum(r["score"] for r in results) / len(results)
    perfect = sum(r["score"] == 1 for r in results)
    md = [
        "# Eval results",
        "",
        f"Extraction accuracy over {len(results)} real plugin repos: **{mean:.1%}** mean, "
        f"{perfect}/{len(results)} perfect. Generated by `python evals/run_evals.py`.",
        "",
        "| Case | Engine | Score | Misses |",
        "|------|--------|-------|--------|",
        *rows,
        "",
    ]
    Path(args.out).write_text("\n".join(md), encoding="utf-8")
    (HERE / "results.json").write_text(json.dumps(results, indent=2), encoding="utf-8")
    print(f"\nmean={mean:.3f} perfect={perfect}/{len(results)}")
    return 1 if mean < args.min_score else 0


if __name__ == "__main__":
    raise SystemExit(main())
