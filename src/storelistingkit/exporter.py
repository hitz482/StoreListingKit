"""Export a ListingKit to a store-ready zip: one folder per store."""

from __future__ import annotations

import io
import json
import re
import zipfile
from pathlib import Path

from .models import ListingKit, StoreCopy
from .stores import full_long_description, spec


def listing_text(copy: StoreCopy) -> str:
    sections = [
        ("TITLE", copy.title),
        ("SHORT DESCRIPTION", copy.short_description),
        ("LONG DESCRIPTION", full_long_description(copy)),
        ("FEATURES", "\n".join(f"- {f}" for f in copy.features)),
        ("TAGS", ", ".join(copy.tags)),
    ]
    head = f"{spec(copy.store)['display_name']} listing (generated by {copy.generated_by})\n"
    return head + "\n".join(f"\n=== {name} ({len(body)} chars) ===\n{body}" for name, body in sections) + "\n"


def slug(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-").lower() or "plugin"


def build_zip(kit: ListingKit, images_root: Path) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        base = slug(kit.profile.title)
        zf.writestr(f"{base}/profile.json", kit.profile.model_dump_json(indent=2))
        issues = [i.model_dump(mode="json") for i in kit.issues]
        zf.writestr(f"{base}/validation.json", json.dumps(issues, indent=2))
        for store, copy in kit.copies.items():
            folder = f"{base}/{store.value}"
            zf.writestr(f"{folder}/listing.txt", listing_text(copy))
            zf.writestr(f"{folder}/listing.json", copy.model_dump_json(indent=2))
            for img in kit.images:
                if img.store != store:
                    continue
                path = images_root / store.value / img.filename
                if path.is_file():
                    zf.write(path, f"{folder}/images/{img.filename}")
    return buf.getvalue()
